// Script chạy trước khi build (prebuild) để sinh file environment cho Angular trên CI/CD (Vercel)
// Không ghi đè nếu đã có file local và không có biến môi trường VISTA_API_URL / API_URL

const fs = require('fs');
const path = require('path');

const envDir = path.resolve(__dirname, '../src/environments');
const targetEnvFile = path.join(envDir, 'environment.ts');
const targetDevEnvFile = path.join(envDir, 'environment.development.ts');

const apiUrl = process.env.VISTA_API_URL || process.env.API_URL;
const geminiApiKey = process.env.GEMINI_API_KEY || '';

if (apiUrl) {
  // Có biến môi trường truyền vào từ Vercel / CI
  const cleanApiUrl = apiUrl.trim().replace(/\/+$/, '');
  const cleanGeminiKey = geminiApiKey.trim();

  const content = `// Auto-generated by scripts/set-env.js at build time - DO NOT COMMIT
export const environment = {
  production: true,
  apiUrl: '${cleanApiUrl}',
  geminiApiKey: '${cleanGeminiKey}'
};
`;

  if (!fs.existsSync(envDir)) {
    fs.mkdirSync(envDir, { recursive: true });
  }

  fs.writeFileSync(targetEnvFile, content, 'utf8');
  fs.writeFileSync(targetDevEnvFile, content, 'utf8');
  console.log(`[set-env] Đã tạo thành công file environment production với apiUrl: ${cleanApiUrl}`);
} else if (fs.existsSync(targetEnvFile)) {
  // Chạy trên môi trường local đã có sẵn file environment
  console.log('[set-env] Sử dụng file environment.ts cục bộ hiện có.');
} else {
  // Thiếu biến môi trường và không có file cục bộ
  console.error('[set-env LỖI] Thiếu biến môi trường VISTA_API_URL (hoặc API_URL) và không tìm thấy file environment.ts.');
  console.error('[set-env LỖI] Vui lòng cấu hình VISTA_API_URL trong cài đặt Environment Variables của Vercel.');
  process.exit(1);
}
